#!/usr/bin/env python3
"""Write sw.js, the service worker that keeps the notes readable offline.

It keeps index.html, the manifest and every image the page names — nothing
else. The cache is named for a hash of those files, so any edit makes a new
worker, and on activation every other "labolic-wiki-" cache is deleted: there
is only ever one copy, however often the notes change.

Run it after every change to the notes (and commit sw.js with them):
  python3 tools/make_sw.py            write sw.js
  python3 tools/make_sw.py --check    exit 1 if sw.js is out of date
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def render():
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    imgs = set(re.findall(r'img/[A-Za-z0-9_/.-]+\.(?:png|webp|jpe?g|gif|svg)', html))
    man = json.loads((ROOT / 'manifest.webmanifest').read_text(encoding='utf-8'))
    imgs |= {i['src'] for i in man.get('icons', [])}
    imgs.discard('img/og-image.png')      # a link-preview image; the page never shows it
    files = ['./', 'index.html', 'manifest.webmanifest'] + sorted(imgs)
    missing = [f for f in files if f != './' and not (ROOT / f).is_file()]
    if missing: sys.exit('error: missing ' + ', '.join(missing))
    h = hashlib.sha256()
    for f in files:
        if f != './': h.update(f.encode()); h.update((ROOT / f).read_bytes())
    cache = f'labolic-wiki-{h.hexdigest()[:10]}'
    body = '\n'.join(f'  {json.dumps(f)},' for f in files)
    return f"""// GENERATED by tools/make_sw.py — do not edit by hand.
// Keeps the notes so they open offline. Online, every request goes to the
// network first (an edit shows at once) and refreshes the kept copy.
const CACHE = '{cache}';
const PREFIX = 'labolic-wiki-';
const FILES = [
{body}
];
const SCOPE = new URL('./', self.location).pathname;
const KEPT = new Set(FILES.map(f => new URL(f, self.location).pathname));

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE)
    .then(c => c.addAll(FILES.map(f => new Request(f, {{ cache: 'reload' }}))))
    .then(() => self.skipWaiting()));
}});

// One cache only. Older copies of the notes go; the game's are left alone.
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE)) return;   // fonts: the network's
  e.respondWith(fetch(req).then(res => {{
    if (res.ok && KEPT.has(url.pathname)) {{
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(url.pathname, copy));
    }}
    return res;
  }}).catch(() => caches.open(CACHE).then(c => c.match(url.pathname)).then(hit =>
    hit || (req.mode === 'navigate' ? caches.match(new URL('./', self.location).href) : Response.error()))));
}});
"""

def main():
    out = ROOT / 'sw.js'
    text = render()
    if '--check' in sys.argv:
        if not out.is_file() or out.read_text(encoding='utf-8') != text:
            print('STALE sw.js: run python3 tools/make_sw.py'); sys.exit(1)
        print('OK   sw.js is up to date'); return
    out.write_text(text, encoding='utf-8')
    print('sw.js:', text.count('\n  "'), 'files,', re.search(r"CACHE = '(.*?)'", text).group(1))

main()
